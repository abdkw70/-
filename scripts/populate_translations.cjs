function translateTitle(title) {
  if (!title) return '';
  let res = title.trim();

  // Try exact or regex replacements first
  for (const [pattern, replacement] of phraseReplacements) {
    if (pattern.test(res)) {
      res = res.replace(pattern, replacement);
    }
  }

  // If still mostly arabic characters, do token-based translation
  if (/[\u0600-\u06FF]/.test(res)) {
    const tokens = res.split(/\s+/);
    const translatedTokens = tokens.map(token => {
      // clean punctuation
      const clean = token.replace(/[.,:;+()]/g, '');
      const mapped = termMap[clean] || termMap[clean.replace(/^ال/, '')];
      if (mapped) {
        return token.replace(clean, mapped);
      }
      return token;
    });
    res = translatedTokens.join(' ');
  }

  // Clean redundant spaces and format nicely
  res = res.replace(/\s+/g, ' ').trim();
  return res;
}

